# config/prompt_config.py
# 提示词模板配置
#
# 设计约束（核心）：
#   L1（系统提示层）和 L2（任务指令层）的内容在整个批次
#   生命周期内必须保持字节级别的完全不变性。任何动态内容
#   （文书元数据、时间戳、任务说明的个性化描述）均须严格
#   限制在 L4 查询层，绝不允许渗入 L1—L3。
#
# 层级划分：
#   L1  系统提示层  ~512 tokens  所有请求共享
#   L2  任务指令层  ~320 tokens  同类任务共享（共 6 种）
#   L3  文书正文层  15K–25K tokens  同文书的 6 次查询共享
#   L4  查询层      ~200 tokens  每次请求独立，不参与缓存

# ── L1：统一系统提示词 ────────────────────────────────────────────
# 措辞固定，不含任何任务特定描述。
# 实际部署前须通过 tokenizer 验证长度约为 512 tokens，
# 若长度偏差超过 ±16 tokens，应调整措辞而非截断。
UNIFIED_SYSTEM_PROMPT: str = (
    "你是一名专业的法律文书分析助手，具备丰富的合同法与商业法律知识。\n"
    "请对提供的合同文书进行客观、准确、全面的法律分析。\n"
    "分析时应重点关注：条款的法律效力、潜在风险点、"
    "各方权利义务的平衡性，\n"
    "以及与现行法律法规的合规性。\n"
    "请以结构化的方式呈现分析结果，区分高风险、中风险和低风险事项。\n"
    "在识别风险时，须注明风险所在条款的编号及原文摘录（不超过50字）。\n"
    "在提取义务时，须标注履行主体、履行期限及违约后果。\n"
    "在归纳日期时，须区分绝对日期（具体日历日）和相对日期"
    "（以某事件为起点的天数）。\n"
    "合规性评估须援引具体法条，格式为《法律名称》第X条第X款。\n"
    "如遇条款措辞模糊或存在多种合理解释的情形，须列出各种解读并"
    "说明对各方的不同含义。\n"
    "分析结论应基于文书明文内容，避免超出文书范围的推断。"
)

# ── L2：任务指令模板（静态，6 种任务类型）────────────────────────
# 每种模板均以换行符结束，确保与 L3 文书正文的拼接边界固定。
# 模板内容绝对不含动态字段（无 f-string 插值，无时间戳）。
STATIC_TASK_TEMPLATES: dict[str, str] = {
    "risk": (
        "请识别以下合同中的风险条款，"
        "按风险等级（高／中／低）分类列示。\n"
        "每项风险须注明：所在条款编号、风险类型、"
        "受影响方及建议的修改方向。\n\n"
    ),
    "obligation": (
        "请提取以下合同中各方的主要义务事项及履行期限。\n"
        "输出格式：义务方 | 义务描述 | 履行期限 | 违约后果。\n\n"
    ),
    "date": (
        "请归纳以下合同中的所有关键日期和截止时间节点。\n"
        "区分绝对日期与相对日期，并标注对应条款编号。\n\n"
    ),
    "compliance": (
        "请评估以下合同与现行法律法规的合规性。\n"
        "对每项合规问题须援引具体法条，"
        "格式为《法律名称》第X条第X款。\n\n"
    ),
    "cross_ref": (
        "请识别以下合同中可能与其他协议存在冲突的条款。\n"
        "重点关注：排他性条款、竞业限制、知识产权归属"
        "及争议管辖条款。\n\n"
    ),
    "summary": (
        "请提供以下合同的核心条款摘要，总字数不超过500字。\n"
        "摘要须涵盖：合同主体、标的、主要权利义务、"
        "违约责任及争议解决方式。\n\n"
    ),
}

# 任务类型列表（顺序固定，用于批处理调度）
TASK_TYPES: list[str] = [
    "risk",
    "obligation",
    "date",
    "compliance",
    "cross_ref",
    "summary",
]


def build_stable_prefix(task_type: str, doc_text: str) -> str:
    """
    构建字节级稳定的完整请求前缀。

    前缀结构：
        [L1 系统提示] + "\\n\\n" +
        [L2 任务指令] +
        [L3 文书正文] + "\\n\\n请根据以上合同内容完成上述分析任务。"

    参数
    ----
    task_type : str
        任务类型键，须为 TASK_TYPES 中的合法值。
    doc_text : str
        经过标准化处理的文书正文（须先通过 text_normalizer 处理）。

    返回
    ----
    str
        完整的用户侧请求内容（传入 messages[user].content）。

    异常
    ----
    KeyError
        若 task_type 不在 STATIC_TASK_TEMPLATES 中则抛出。
    """
    if task_type not in STATIC_TASK_TEMPLATES:
        raise KeyError(
            f"未知任务类型 '{task_type}'，"
            f"合法值为 {list(STATIC_TASK_TEMPLATES.keys())}"
        )
    template = STATIC_TASK_TEMPLATES[task_type]
    return (
        UNIFIED_SYSTEM_PROMPT
        + "\n\n"
        + template
        + doc_text
        + "\n\n请根据以上合同内容完成上述分析任务。"
    )
