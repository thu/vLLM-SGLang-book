def build_synthetic_dataset(
    n_procurement: int = 60,
    n_labor: int = 60,
    n_software: int = 60,
    seed: int = 42,
) -> list[ContractDocument]:
    """
    构建合成合同文书数据集。

    参数
    ----
    n_procurement : int
        采购框架协议数量，默认 60 份。
    n_labor : int
        劳动合同数量，默认 60 份。
    n_software : int
        软件服务协议数量，默认 60 份。
    seed : int
        随机种子，保证数据集可重复生成。

    返回
    ----
    list[ContractDocument]
        共 (n_procurement + n_labor + n_software) 份文书，
        顺序为：采购协议 → 劳动合同 → 软件服务协议。
    """
    from data.text_normalizer import normalize_document_text

    rng = random.Random(seed)
    docs: list[ContractDocument] = []

    generators = [
        (ContractType.PROCUREMENT, n_procurement,
         _generate_procurement_contract, "PROC"),
        (ContractType.LABOR, n_labor,
         _generate_labor_contract, "LABOR"),
        (ContractType.SOFTWARE_SERVICE, n_software,
         _generate_software_contract, "SVC"),
    ]

    for contract_type, count, gen_fn, prefix in generators:
        for i in range(count):
            doc_id = f"{prefix}-{i+1:04d}"
            raw_text = gen_fn(doc_id, rng)
            normalized = normalize_document_text(raw_text)
            docs.append(ContractDocument(
                doc_id=doc_id,
                contract_type=contract_type,
                text=normalized,
                metadata={
                    "type": contract_type.value,
                    "index": i,
                },
            ))

    return docs
