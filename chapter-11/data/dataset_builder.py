# data/dataset_builder.py
# 合成测试数据集构建（ch11_code_01）
#
# 本模块生成三类合同文书的合成语料，用于本章的性能测试。
# 合成数据的设计目标：
#   1. token 长度分布与真实法律文书一致（均值约 18K–22K tokens）
#   2. 同类文书共享大量标准化条款，以测试跨文书缓存复用
#   3. 不同文书在金额、日期、主体名称等字段上存在差异
#
# 注意：本模块生成的是结构性占位文本，
# 不代表真实法律意见，不可用于实际法律用途。

from __future__ import annotations

import hashlib
import random
from dataclasses import dataclass, field
from enum import Enum


class ContractType(str, Enum):
    PROCUREMENT = "procurement"   # 采购框架协议
    LABOR = "labor"               # 劳动合同
    SOFTWARE_SERVICE = "software" # 软件服务协议


@dataclass
class ContractDocument:
    """单份合同文书的数据结构。"""
    doc_id: str
    contract_type: ContractType
    # 经过标准化处理后的正文文本
    text: str
    # 由 tokenizer 填充的实际 token 数（初始为 0）
    token_count: int = 0
    metadata: dict = field(default_factory=dict)

    def content_hash(self) -> str:
        """计算文书正文的 MD5 哈希，用于快速一致性校验。"""
        return hashlib.md5(
            self.text.encode("utf-8")
        ).hexdigest()


